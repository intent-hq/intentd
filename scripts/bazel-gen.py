#!/usr/bin/env python3
"""Generate the Bazel files that mirror the Cargo workspace.

Cargo is the source of truth. This script reads `cargo metadata` and
rust-toolchain.toml and writes:

  * crates/<crate>/BUILD.bazel           one per workspace member
  * bazel/generated.MODULE.bazel         Rust toolchain pin + crate_universe manifests

Run it after changing a Cargo.toml (new crate, first-party dependency, feature,
build script) or rust-toolchain.toml:

    python3 scripts/bazel-gen.py          # rewrite the generated files
    python3 scripts/bazel-gen.py --check  # exit 1 if any generated file is stale

Third-party dependencies are not listed here: the generated BUILD files call
crate_universe's `all_crate_deps()`, which resolves them from Cargo.toml and
Cargo.lock on every fetch. Cargo.lock is the only lock (there is no separate
crate_universe lockfile), so a third-party change needs no Bazel edit.

Per-crate behavior that cannot be derived from Cargo metadata lives in the
OVERRIDES table below, so every hand decision is in one reviewable place.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEADER = (
    "# @generated by scripts/bazel-gen.py from Cargo metadata. Do not edit by hand;\n"
    "# change Cargo.toml (or OVERRIDES in the script) and rerun the generator.\n"
)

# Files a crate embeds at compile time (include_str!/include_bytes!/sqlx::migrate!)
# live next to its sources. Everything in the package except Rust sources, tests
# and build metadata is declared as compile data so new resources need no edit.
COMPILE_DATA_EXCLUDES = [
    "**/*.rs",
    "BUILD.bazel",
    "Cargo.toml",
    "target/**",
    "tests/**",
    "benches/**",
    "examples/**",
]

# Hand decisions that Cargo metadata cannot express. Keys are Cargo package names.
#   build_script: "cargo" runs build.rs as a cargo_build_script (default when the
#       crate has one); "stamp" replaces it with Bazel workspace-status stamping.
#   rustc_env_files: extra env files passed to rustc.
OVERRIDES: dict[str, dict] = {
    # build.rs shells out to `git` for the commit, which is not hermetic and does
    # not work in the sandbox. The commit comes from bazel/workspace_status.sh
    # instead (it honors the same INTENTD_BUILD_COMMIT override), and reaches
    # rustc as INTENTD_EMBEDDED_BUILD_COMMIT, the variable build.rs would set.
    "intent-transport": {
        "build_script": "stamp",
        "rustc_env_files": ["//bazel:build_commit_env"],
    },
}


def cargo_metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--no-deps", "--locked", "--offline"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def rust_version() -> str:
    data = tomllib.loads((ROOT / "rust-toolchain.toml").read_text())
    return data["toolchain"]["channel"]


def starlark_list(items: list[str], indent: str = "    ") -> str:
    if not items:
        return "[]"
    if len(items) == 1:
        return f'["{items[0]}"]'
    inner = "".join(f'{indent}    "{item}",\n' for item in items)
    return f"[\n{inner}{indent}]"


def default_features(features: dict[str, list[str]]) -> list[str]:
    """Resolve the crate's own `default` feature set (no `dep:` entries)."""
    enabled: set[str] = set()
    stack = list(features.get("default", []))
    while stack:
        feature = stack.pop()
        if feature.startswith("dep:") or "/" in feature or feature in enabled:
            continue
        enabled.add(feature)
        stack.extend(features.get(feature, []))
    return sorted(enabled)


def enabled_optional_deps(features: dict[str, list[str]], enabled: list[str]) -> set[str]:
    deps: set[str] = set()
    for feature in enabled:
        for item in features.get(feature, []):
            if item.startswith("dep:"):
                deps.add(item[4:])
    return deps


class Workspace:
    def __init__(self, metadata: dict) -> None:
        members = set(metadata["workspace_members"])
        self.packages = [p for p in metadata["packages"] if p["id"] in members]
        self.by_name = {p["name"]: p for p in self.packages}

    def package_dir(self, package: dict) -> Path:
        return Path(package["manifest_path"]).parent.relative_to(ROOT)

    def lib_label(self, name: str, from_pkg: dict) -> str:
        target = self.by_name[name]
        crate_name = lib_target(target)["name"]
        pkg_dir = self.package_dir(target).as_posix()
        if target is from_pkg:
            return f":{crate_name}"
        return f"//{pkg_dir}:{crate_name}"


def lib_target(package: dict) -> dict:
    for target in package["targets"]:
        if any(kind in ("lib", "proc-macro") for kind in target["kind"]):
            return target
    raise KeyError(f"{package['name']} has no library target")


def first_party_deps(ws: Workspace, package: dict, kinds: set[str | None]) -> tuple[list[str], list[str]]:
    """Return (deps, proc_macro_deps) labels for path dependencies of `package`."""
    features = default_features(package["features"])
    optional = enabled_optional_deps(package["features"], features)
    deps: set[str] = set()
    proc_macros: set[str] = set()
    for dep in package["dependencies"]:
        if dep["name"] not in ws.by_name or dep["kind"] not in kinds:
            continue
        if dep["optional"] and dep["name"] not in optional:
            continue
        if dep["target"] is not None:
            raise SystemExit(
                f"{package['name']}: target-specific path dependency {dep['name']} "
                f"({dep['target']}) is not supported yet; extend scripts/bazel-gen.py"
            )
        if dep.get("rename"):
            raise SystemExit(f"{package['name']}: renamed path dependency {dep['name']} is not supported yet")
        dep_pkg = ws.by_name[dep["name"]]
        label = ws.lib_label(dep["name"], package)
        if "proc-macro" in lib_target(dep_pkg)["kind"]:
            proc_macros.add(label)
        else:
            deps.add(label)
    return sorted(deps), sorted(proc_macros)


def relative_src(package: dict, target: dict) -> str:
    pkg_dir = Path(package["manifest_path"]).parent
    return Path(target["src_path"]).relative_to(pkg_dir).as_posix()


def render_build(ws: Workspace, package: dict) -> str:
    name = package["name"]
    override = OVERRIDES.get(name, {})
    features = default_features(package["features"])
    targets = package["targets"]
    lib = next((t for t in targets if {"lib", "proc-macro"} & set(t["kind"])), None)
    bins = [t for t in targets if "bin" in t["kind"]]
    build_rs = next((t for t in targets if "custom-build" in t["kind"]), None)
    build_mode = override.get("build_script", "cargo") if build_rs else None

    rules = set()
    if lib is not None:
        rules.add("rust_proc_macro" if "proc-macro" in lib["kind"] else "rust_library")
    if bins:
        rules.add("rust_binary")
    if build_mode == "cargo":
        rules.add("cargo_build_script")

    out = [HEADER]
    out.append('load("@crates//:defs.bzl", "aliases", "all_crate_deps")\n')
    if "cargo_build_script" in rules:
        out.append('load("@rules_rust//cargo:defs.bzl", "cargo_build_script")\n')
    rust_rules = sorted(rules - {"cargo_build_script"})
    out.append(
        'load("@rules_rust//rust:defs.bzl", '
        + ", ".join(f'"{rule}"' for rule in rust_rules)
        + ")\n\n"
    )
    out.append('package(default_visibility = ["//visibility:public"])\n\n')
    out.append(
        "COMPILE_DATA = glob(\n    [\"**\"],\n    exclude = "
        + starlark_list(COMPILE_DATA_EXCLUDES, "    ")
        + ",\n    allow_empty = True,\n)\n\n"
    )

    normal_deps, normal_macros = first_party_deps(ws, package, {None})
    common = [
        f'    edition = "{package["edition"]}",\n',
        f'    version = "{package["version"]}",\n',
    ]
    feature_line = f"    crate_features = {starlark_list(features, '    ')},\n"

    build_dep: list[str] = []
    if build_mode == "cargo":
        out.append("cargo_build_script(\n")
        out.append('    name = "build_script",\n')
        out.append(f'    srcs = ["{relative_src(package, build_rs)}"],\n')
        out.append("    aliases = aliases(build = True),\n")
        out.append("    compile_data = COMPILE_DATA,\n")
        out.append("    data = COMPILE_DATA,\n")
        out.extend(common)
        out.append(feature_line)
        out.append("    proc_macro_deps = all_crate_deps(build_proc_macro = True),\n")
        out.append("    deps = all_crate_deps(build = True),\n")
        out.append(")\n\n")
        build_dep = [":build_script"]

    env_files = override.get("rustc_env_files", [])

    def deps_expr(extra: list[str]) -> str:
        expr = "all_crate_deps(normal = True)"
        if extra:
            expr += " + " + starlark_list(extra, "    ")
        return expr

    def macro_expr(extra: list[str]) -> str:
        expr = "all_crate_deps(proc_macro = True)"
        if extra:
            expr += " + " + starlark_list(extra, "    ")
        return expr

    if lib is not None:
        rule = "rust_proc_macro" if "proc-macro" in lib["kind"] else "rust_library"
        out.append(f"{rule}(\n")
        out.append(f'    name = "{lib["name"]}",\n')
        out.append('    srcs = glob(["src/**/*.rs"]),\n')
        out.append(f'    crate_root = "{relative_src(package, lib)}",\n')
        out.append("    aliases = aliases(),\n")
        out.append("    compile_data = COMPILE_DATA,\n")
        out.extend(common)
        out.append(feature_line)
        out.append(f"    proc_macro_deps = {macro_expr(normal_macros)},\n")
        if env_files:
            out.append(f"    rustc_env_files = {starlark_list(env_files, '    ')},\n")
        out.append(f"    deps = {deps_expr(normal_deps + build_dep)},\n")
        out.append(")\n\n")

    for bin_target in bins:
        extra = list(normal_deps + build_dep)
        if lib is not None:
            extra.append(f":{lib['name']}")
        out.append("rust_binary(\n")
        out.append(f'    name = "{bin_target["name"]}",\n')
        out.append('    srcs = glob(["src/**/*.rs"]),\n')
        out.append(f'    crate_root = "{relative_src(package, bin_target)}",\n')
        out.append("    aliases = aliases(),\n")
        out.append("    compile_data = COMPILE_DATA,\n")
        out.extend(common)
        out.append(feature_line)
        out.append(f"    proc_macro_deps = {macro_expr(normal_macros)},\n")
        if env_files:
            out.append(f"    rustc_env_files = {starlark_list(env_files, '    ')},\n")
        out.append(f"    deps = {deps_expr(sorted(set(extra)))},\n")
        out.append(")\n\n")

    return "".join(out).rstrip("\n") + "\n"


def render_module(ws: Workspace) -> str:
    manifests = ["//:Cargo.toml"] + sorted(
        f"//{ws.package_dir(p).as_posix()}:Cargo.toml" for p in ws.packages
    )
    manifest_lines = "".join(f'        "{m}",\n' for m in manifests)
    return f'''{HEADER}
# Rust toolchain, pinned to rust-toolchain.toml's channel.
rust = use_extension("@rules_rust//rust:extensions.bzl", "rust")
rust.toolchain(
    edition = "2021",
    versions = ["{rust_version()}"],
)
use_repo(rust, "rust_toolchains")

register_toolchains("@rust_toolchains//:all")

# Third-party crates, resolved from the Cargo workspace. Crate annotations
# (build-script environment, native-library tweaks) are in
# bazel/crates.MODULE.bazel.
crate = use_extension("@rules_rust//crate_universe:extensions.bzl", "crate")
crate.from_cargo(
    name = "crates",
    cargo_lockfile = "//:Cargo.lock",
    manifests = [
{manifest_lines}    ],
)
use_repo(crate, "crates")
'''


def generated_files() -> dict[Path, str]:
    ws = Workspace(cargo_metadata())
    files = {ROOT / "bazel" / "generated.MODULE.bazel": render_module(ws)}
    for package in ws.packages:
        files[ROOT / ws.package_dir(package) / "BUILD.bazel"] = render_build(ws, package)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if any generated file is stale")
    args = parser.parse_args()

    stale = []
    for path, content in generated_files().items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.write_text(content)

    expected = set(generated_files()) if args.check else None
    if args.check:
        for build in sorted(ROOT.glob("crates/*/BUILD.bazel")):
            if build not in expected:
                stale.append(build.relative_to(ROOT))

    if args.check and stale:
        print("Bazel files are out of date with Cargo metadata:", file=sys.stderr)
        for path in stale:
            print(f"  {path}", file=sys.stderr)
        print("Run: python3 scripts/bazel-gen.py", file=sys.stderr)
        return 1
    for path in stale:
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
