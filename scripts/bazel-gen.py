#!/usr/bin/env python3
"""Generate the Bazel files that mirror the Cargo workspace.

Cargo is the source of truth. This script reads `cargo metadata`,
rust-toolchain.toml and .config/nextest.toml and writes:

  * BUILD.bazel                          root aliases and workspace file groups
  * crates/<crate>/BUILD.bazel           one per workspace member
  * bazel/generated.MODULE.bazel         Rust toolchain pin + crate_universe hubs
  * bazel/prod-workspace/**              Cargo manifests without dev-dependencies

Run it after changing a Cargo.toml (new crate, first-party dependency, feature,
build script, test target), rust-toolchain.toml or .config/nextest.toml:

    python3 scripts/bazel-gen.py          # rewrite the generated files
    python3 scripts/bazel-gen.py --check  # exit 1 if any generated file is stale

Third-party dependencies are not listed here: the generated BUILD files call
crate_universe's `all_crate_deps()`, which resolves them from Cargo.toml and
Cargo.lock. Cargo.lock is the only dependency lock; MODULE.bazel.lock caches
crate_universe's resolution of it.

Two dependency graphs, like Cargo's resolver 2:

  * Production (`@crates`, first-party targets named after the crate):
    third-party features as `cargo build` resolves them. crate_universe always
    unifies dev-dependency features, so this hub resolves
    bazel/prod-workspace, a copy of the manifests with dev-dependencies removed.
  * Test (`@crates_dev`, first-party targets suffixed `_dev`): features as
    `cargo test --workspace` resolves them, including dev-only features such as
    tokio's `test-util` and first-party `test-support` features. Every test
    target builds against this graph only.

Per-crate behavior that cannot be derived from Cargo metadata lives in the
OVERRIDES, MANUAL_TESTS and FIXTURE_TESTS tables below, so every hand decision
is in one reviewable place.
"""

