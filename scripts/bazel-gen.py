class NextestPolicy:
    """The parts of .config/nextest.toml that map onto Bazel.

    * overrides with `threads-required = 'num-test-threads'` or a test-group:
      whole binaries become `exclusive` targets; individual tests move to a
      `<target>_serial` companion that runs them one at a time, exclusively.
    * retries and slow-timeout map onto .bazelrc flags (see bazel/README.md).
    * priority has no Bazel equivalent and is ignored.
    """

    def __init__(self, path: Path) -> None:
        data = tomllib.loads(path.read_text()) if path.exists() else {}
        self.exclusive_binaries: set[str] = set()
        # (binary id or None for every binary, substring pattern)
        self.serial_tests: list[tuple[str | None, str]] = []
        for override in data.get("profile", {}).get("default", {}).get("overrides", []):
            serial = override.get("threads-required") == "num-test-threads" or "test-group" in override
            if not serial:
                continue
            for binary, test in parse_filter(override["filter"]):
                if test is None:
                    if binary is None:
                        raise SystemExit(f"nextest override matches every test: {override['filter']}")
                    self.exclusive_binaries.add(binary)
                else:
                    self.serial_tests.append((binary, test))

    def serial_patterns(self, binary_id: str, sources: str) -> list[str]:
        """Serial tests of one binary.

        Patterns that name no binary apply to every binary in nextest; here they
        only split binaries whose sources mention the pattern's last identifier,
        so other binaries keep a single target.
        """
        patterns = set()
        for binary, test in self.serial_tests:
            if binary == binary_id:
                patterns.add(test)
            elif binary is None:
                parts = [re.escape(part) for part in test.split("::") if part]
                if test.endswith("::"):
                    mentions = [rf"\bmod\s+{part}\b" for part in parts]
                else:
                    mentions = [rf"\bmod\s+{part}\b" for part in parts[:-1]]
                    mentions.append(rf"\b(?:fn|mod)\s+\w*{parts[-1]}\w*")
                if all(re.search(mention, sources) for mention in mentions):
                    patterns.add(test)
        return sorted(patterns)


def parse_filter(text: str) -> list[tuple[str | None, str | None]]:
    """Parse the nextest filterset subset used here into OR-ed (binary, test) pairs.

    Supports `binary_id(=X)`, `test(=X)`, `test(X)`, `test(/X/)` (X without regex
    metacharacters), `|`, `&` and parentheses. Each pair means "tests in binary
    (any binary when None) whose name contains test (all when None)".
    """
    tokens = re.findall(r"binary_id\(=[^)]*\)|test\([^)]*\)|[|&()]", text)
    if re.sub(r"\s+", "", "".join(tokens)) != re.sub(r"\s+", "", text):
        raise SystemExit(f"unsupported nextest filter, extend scripts/bazel-gen.py: {text}")
    pos = 0

    def atom() -> list[tuple[str | None, str | None]]:
        nonlocal pos
        token = tokens[pos]
        pos += 1
        if token == "(":
            result = disjunction()
            pos += 1
            return result
        if token.startswith("binary_id"):
            return [(token[len("binary_id(="):-1], None)]
        value = token[len("test("):-1]
        if value.startswith("="):
            value = value[1:]
        elif value.startswith("/") and value.endswith("/"):
            value = value[1:-1]
        if re.search(r"[\\^$.*+?\[\]{}|]", value):
            raise SystemExit(f"unsupported regex in nextest filter, extend scripts/bazel-gen.py: {value}")
        return [(None, value)]

    def conjunction() -> list[tuple[str | None, str | None]]:
        nonlocal pos
        result = atom()
        while pos < len(tokens) and tokens[pos] == "&":
            pos += 1
            right = atom()
            merged = []
            for b1, t1 in result:
                for b2, t2 in right:
                    if (b1 and b2 and b1 != b2) or (t1 and t2):
                        raise SystemExit(f"unsupported nextest filter, extend scripts/bazel-gen.py: {text}")
                    merged.append((b1 or b2, t1 or t2))
            result = merged
        return result

    def disjunction() -> list[tuple[str | None, str | None]]:
        nonlocal pos
        result = conjunction()
        while pos < len(tokens) and tokens[pos] == "|":
            pos += 1
            result += conjunction()
        return result

    return disjunction()


# --- Cargo workspace ---------------------------------------------------------


class Workspace:
    def __init__(self, metadata: dict) -> None:
        members = set(metadata["workspace_members"])
        self.packages = sorted((p for p in metadata["packages"] if p["id"] in members), key=lambda p: p["name"])
        self.by_name = {p["name"]: p for p in self.packages}
        self.prod_features = self.resolve_features({None, "build"})
        self.dev_features = self.resolve_features({None, "build", "dev"})

    def package_dir(self, package: dict) -> Path:
        return Path(package["manifest_path"]).parent.relative_to(ROOT)

    def resolve_features(self, kinds: set[str | None]) -> dict[str, list[str]]:
        """First-party features as Cargo unifies them over the workspace.

        With `kinds` = normal + build this is `cargo build --workspace`; adding
        dev is `cargo test --workspace`.
        """
        enabled: dict[str, set[str]] = {p["name"]: set() for p in self.packages}

        def enable(name: str, feature: str) -> bool:
            package = self.by_name[name]
            if feature in enabled[name]:
                return False
            if feature != "default" and feature not in package["features"]:
                raise SystemExit(f"{name}: unknown feature {feature}")
            enabled[name].add(feature)
            return True

        for package in self.packages:
            if "default" in package["features"]:
                enable(package["name"], "default")
        changed = True
        while changed:
            changed = False
            for package in self.packages:
                name = package["name"]
                for feature in list(enabled[name]):
                    for item in package["features"].get(feature, []):
                        if item.startswith("dep:"):
                            continue
                        if "/" in item:
                            dep, _, sub = item.partition("/")
                            dep = dep.rstrip("?")
                            if dep in self.by_name:
                                changed |= enable(dep, sub)
                        elif item in package["features"]:
                            changed |= enable(name, item)
                for dep in package["dependencies"]:
                    if dep["name"] not in self.by_name or dep["kind"] not in kinds:
                        continue
                    if dep["optional"] and dep["name"] not in self.optional_deps(package, enabled[name]):
                        continue
                    for feature in dep["features"]:
                        changed |= enable(dep["name"], feature)
                    if dep["uses_default_features"] and "default" in self.by_name[dep["name"]]["features"]:
                        changed |= enable(dep["name"], "default")
        return {name: sorted(f for f in features if f != "default") for name, features in enabled.items()}

    @staticmethod
    def optional_deps(package: dict, features: set[str]) -> set[str]:
        deps: set[str] = set()
        for feature in features:
            for item in package["features"].get(feature, []):
                if item.startswith("dep:"):
                    deps.add(item[4:])
                elif "/" in item and not item.split("/")[0].endswith("?"):
                    deps.add(item.split("/")[0])
        return deps

    def first_party_deps(self, package: dict, kinds: set[str | None], dev_graph: bool) -> tuple[list[str], list[str]]:
        """Return (deps, proc_macro_deps) labels for path dependencies of `package`."""
        features = set(self.dev_features[package["name"]] if dev_graph else self.prod_features[package["name"]])
        if "default" in package["features"]:
            features.add("default")
        optional = self.optional_deps(package, features)
        deps: set[str] = set()
        proc_macros: set[str] = set()
        for dep in package["dependencies"]:
            if dep["name"] not in self.by_name or dep["kind"] not in kinds:
                continue
            if dep["optional"] and dep["name"] not in optional:
                continue
            if dep["target"] is not None:
                raise SystemExit(
                    f"{package['name']}: target-specific path dependency {dep['name']} "
                    f"({dep['target']}) is not supported yet; extend scripts/bazel-gen.py"
                )
            if dep.get("rename"):
                raise SystemExit(f"{package['name']}: renamed path dependency {dep['name']} is not supported yet")
            if dep["name"] == package["name"]:
                continue
            dep_pkg = self.by_name[dep["name"]]
            label = self.lib_label(dep_pkg, package, dev_graph)
            if "proc-macro" in lib_target(dep_pkg)["kind"]:
                proc_macros.add(label)
            else:
                deps.add(label)
        return sorted(deps), sorted(proc_macros)

    def lib_label(self, target: dict, from_pkg: dict, dev_graph: bool) -> str:
        name = lib_target(target)["name"] + ("_dev" if dev_graph else "")
        if target is from_pkg:
            return f":{name}"
        return f"//{self.package_dir(target).as_posix()}:{name}"


def lib_target(package: dict) -> dict:
    for target in package["targets"]:
        if any(kind in ("lib", "proc-macro") for kind in target["kind"]):
            return target
    raise KeyError(f"{package['name']} has no library target")


def relative_src(package: dict, target: dict) -> str:
    pkg_dir = Path(package["manifest_path"]).parent
    return Path(target["src_path"]).relative_to(pkg_dir).as_posix()


def has_lints(package: dict) -> bool:
    return "lints" in tomllib.loads(Path(package["manifest_path"]).read_text())


