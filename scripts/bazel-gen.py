def cargo_metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--no-deps", "--locked", "--offline"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def rust_version() -> str:
    data = tomllib.loads((ROOT / "rust-toolchain.toml").read_text())
    return data["toolchain"]["channel"]


def starlark_list(items: list[str], indent: str = "    ") -> str:
    if not items:
        return "[]"
    if len(items) == 1:
        return f"[{json.dumps(items[0])}]"
    inner = "".join(f"{indent}    {json.dumps(item)},\n" for item in items)
    return f"[\n{inner}{indent}]"


def starlark_dict(items: dict[str, str], indent: str = "    ") -> str:
    if not items:
        return "{}"
    inner = "".join(f"{indent}    {json.dumps(k)}: {json.dumps(v)},\n" for k, v in sorted(items.items()))
    return f"{{\n{inner}{indent}}}"


