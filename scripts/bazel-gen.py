class Rule:
    """A Starlark rule call; attributes keep insertion order."""

    def __init__(self, kind: str, **attrs: object) -> None:
        self.kind = kind
        self.attrs = attrs

    def render(self) -> str:
        out = [f"{self.kind}(\n"]
        for key, value in self.attrs.items():
            if value is None:
                continue
            if isinstance(value, Raw):
                text = value.text
            elif isinstance(value, list):
                text = starlark_list(value)
            elif isinstance(value, dict):
                text = starlark_dict(value)
            elif isinstance(value, bool):
                text = "True" if value else "False"
            else:
                text = json.dumps(value)
            out.append(f"    {key} = {text},\n")
        out.append(")\n")
        return "".join(out)


class Raw:
    def __init__(self, text: str) -> None:
        self.text = text


def concat(expr: str, extra: list[str]) -> Raw:
    return Raw(expr + (" + " + starlark_list(extra) if extra else ""))


def crate_sources(pkg_root: Path, pattern: str) -> str:
    return "\n".join(p.read_text(errors="replace") for p in sorted(pkg_root.glob(pattern)) if p.is_file())


def module_shards(pkg_root: Path, crate_root: str, count: int) -> list[list[str]]:
    """Group the crate's top-level modules into `count` buckets of similar size."""
    root = pkg_root / crate_root
    src = root.parent
    names = sorted(set(re.findall(r"^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+(\w+)\s*[;{]", root.read_text(), re.M)))
    weights = []
    for module in names:
        files = [src / f"{module}.rs", *(src / module).rglob("*.rs")] if (src / module).is_dir() else [src / f"{module}.rs"]
        weights.append((sum(f.stat().st_size for f in files if f.is_file()), module))
    buckets: list[tuple[int, list[str]]] = [(0, []) for _ in range(count)]
    for weight, module in sorted(weights, reverse=True):
        buckets.sort(key=lambda b: b[0])
        total, members = buckets[0]
        buckets[0] = (total + weight, members + [module])
    return [sorted(members) for _, members in buckets if members]


SRC_GLOB = 'glob(["src/**/*.rs"], exclude = INCLUDED_SRCS)'


def integration_test_roots(pkg_root: Path) -> list[tuple[str, str]]:
    """(name, crate root) of each file Cargo autodiscovers as an integration test.

    Mirrors `integration_test_roots` in bazel/rust_integration_tests.bzl.
    """
    roots = [(p.stem, f"tests/{p.name}") for p in pkg_root.glob("tests/*.rs") if p.is_file()]
    roots += [(p.parent.name, f"tests/{p.parent.name}/main.rs") for p in pkg_root.glob("tests/*/main.rs") if p.is_file()]
    return sorted(roots)


def reads_workspace_sources_by_name(test_name: str) -> bool:
    """Mirrors `reads_workspace_sources` in bazel/rust_integration_tests.bzl."""
    return test_name.endswith("_lint")


def render_overrides(overrides: dict[str, dict]) -> str:
    if not overrides:
        return "{}"

    def value(v: object) -> str:
        return ("True" if v else "False") if isinstance(v, bool) else json.dumps(v)

    lines = []
    for test, override in sorted(overrides.items()):
        fields = ", ".join(f"{json.dumps(k)}: {value(v)}" for k, v in sorted(override.items()))
        lines.append(f"        {json.dumps(test)}: {{{fields}}},\n")
    return "{\n" + "".join(lines) + "    }"
_INCLUDE_RE = re.compile(r'\binclude!\s*\(\s*"([^"]+\.rs)"\s*\)')


def included_fragments(pkg_root: Path) -> list[str]:
    """Package-relative .rs files under src/ that are only reached via include!()."""
    found = set()
    for path in sorted((pkg_root / "src").rglob("*.rs")):
        for rel in _INCLUDE_RE.findall(path.read_text(errors="replace")):
            target = (path.parent / rel).resolve()
            try:
                found.add(target.relative_to(pkg_root.resolve()).as_posix())
            except ValueError:
                continue
    return sorted(f for f in found if f.startswith("src/") and (pkg_root / f).is_file())


def render_build(ws: Workspace, package: dict, nextest: NextestPolicy) -> str:
    name = package["name"]
    pkg_dir = ws.package_dir(package).as_posix()
    pkg_root = ROOT / pkg_dir
    prod_pkg = f"{PROD_WORKSPACE.as_posix()}/{pkg_dir}"
    override = OVERRIDES.get(name, {})
    targets = package["targets"]
    lib = next((t for t in targets if {"lib", "proc-macro"} & set(t["kind"])), None)
    is_proc_macro = lib is not None and "proc-macro" in lib["kind"]
    bins = [t for t in targets if "bin" in t["kind"]]
    tests = [t for t in targets if "test" in t["kind"]]
    build_rs = next((t for t in targets if "custom-build" in t["kind"]), None)
    build_mode = override.get("build_script", "cargo") if build_rs else None
    # Production only: the test graph is unstamped (like a Cargo build outside a
    # git checkout), so a new commit does not invalidate every cached test.
    env_files = override.get("rustc_env_files", [])
    lint_config = ":cargo_lints" if has_lints(package) else None
    # The version comes from Cargo.toml at load time (bazel/cargo_versions.bzl),
    # so a release bump needs no regeneration.
    common = {"edition": package["edition"], "version": Raw("CRATE_VERSION")}
    # Test-graph actions run outside the sandbox (TEST_GRAPH_TAGS), so rules_rust's
    # CARGO_MANIFEST_DIR is the real execroot, whose top-level entries link to
    # the source tree. Tests embed it with env!() and hand paths below it to
    # child processes, as under Cargo, so it must outlive the compile action.
    # Cargo passes the crate's rust-version to rustc and clippy; clippy uses it
    # as the MSRV, which keeps lints for newer std APIs quiet. rules_rust does
    # not set it.
    pkg_env = {"CARGO_PKG_RUST_VERSION": package["rust_version"]} if package.get("rust_version") else {}
    test_env: dict[str, str] = dict(pkg_env)

    rules: list[Rule] = []
    used = {"rust_test"} if (tests or bins or lib) else set()

    if lint_config:
        rules.append(Rule("extract_cargo_lints", name="cargo_lints", manifest="Cargo.toml", workspace="//:Cargo.toml"))

    rules.append(Rule("filegroup", name="test_data_files", srcs=Raw(
        'glob(["**"], exclude = ["**/*.rs", "BUILD.bazel", "target/**"], allow_empty = True)')))
    rules.append(Rule("filegroup", name="rust_source_files", srcs=Raw(
        'glob(["**/*.rs"], exclude = ["target/**"], allow_empty = True)')))

    def graph(dev: bool) -> dict:
        if dev:
            return {
                "crate_deps": "dev_crate_deps",
                "aliases": "dev_aliases",
                "pkg": "",
                "suffix": "_dev",
                "features": ws.dev_features[name],
            }
        return {
            "crate_deps": "all_crate_deps",
            "aliases": "aliases",
            "pkg": f'package_name = "{prod_pkg}", ',
            "suffix": "",
            "features": ws.prod_features[name],
        }

    def crate_deps(g: dict, **kinds: bool) -> str:
        args = ", ".join(f"{k} = True" for k in kinds)
        return f"{g['crate_deps']}({g['pkg']}{args})"

    for dev in (False, True):
        g = graph(dev)
        normal_deps, normal_macros = ws.first_party_deps(package, {None}, dev)
        build_dep: list[str] = []
        if build_mode == "cargo":
            used.add("cargo_build_script")
            build_dep = [f":build_script{g['suffix']}"]
            rules.append(Rule(
                "cargo_build_script",
                name=f"build_script{g['suffix']}",
                srcs=[relative_src(package, build_rs)],
                aliases=Raw(f"{g['aliases']}({g['pkg']}build = True)"),
                compile_data=Raw("COMPILE_DATA + INCLUDED_SRCS"),
                data=Raw("COMPILE_DATA"),
                **common,
                crate_features=g["features"],
                proc_macro_deps=Raw(crate_deps(g, build_proc_macro=True)),
                deps=Raw(crate_deps(g, build=True)),
            ))
        if lib is not None:
            rule = "rust_proc_macro" if is_proc_macro else "rust_library"
            used.add(rule)
            rules.append(Rule(
                rule,
                name=lib["name"] + g["suffix"],
                crate_name=lib["name"] if dev else None,
                # Unsandboxed, a pipelined full compile rewrites the read-only
                # .rmeta its metadata action already produced.
                disable_pipelining=True if dev and not is_proc_macro else None,
                srcs=Raw(SRC_GLOB),
                crate_root=relative_src(package, lib),
                aliases=Raw(f"{g['aliases']}({g['pkg'].rstrip(', ')})"),
                compile_data=Raw("COMPILE_DATA + INCLUDED_SRCS"),
                **common,
                crate_features=g["features"],
                lint_config=lint_config,
                proc_macro_deps=concat(crate_deps(g, proc_macro=True), normal_macros),
                rustc_env=(test_env if dev else pkg_env) or None,
                rustc_env_files=(env_files or None) if not dev else None,
                tags=TEST_GRAPH_TAGS if dev else None,
                deps=concat(crate_deps(g, normal=True), normal_deps + build_dep),
            ))
        for bin_target in bins:
            used.add("rust_binary")
            extra = list(normal_deps + build_dep)
            if lib is not None and not is_proc_macro:
                extra.append(f":{lib['name']}{g['suffix']}")
            rules.append(Rule(
                "rust_binary",
                name=bin_target["name"] + g["suffix"],
                srcs=Raw(SRC_GLOB),
                crate_root=relative_src(package, bin_target),
                aliases=Raw(f"{g['aliases']}({g['pkg'].rstrip(', ')})"),
                compile_data=Raw("COMPILE_DATA + INCLUDED_SRCS"),
                **common,
                crate_features=g["features"],
                lint_config=lint_config,
                proc_macro_deps=concat(crate_deps(g, proc_macro=True), normal_macros),
                rustc_env=(test_env if dev else pkg_env) or None,
                rustc_env_files=(env_files or None) if not dev else None,
                tags=TEST_GRAPH_TAGS if dev else None,
                deps=concat(crate_deps(g, normal=True), sorted(set(extra))),
            ))
            if dev:
                # Integration tests run the binary under its Cargo name.
                used.add("copy_file")
                rules.append(Rule(
                    "copy_file",
                    name=f"{bin_target['name']}_test_bin",
                    src=f":{bin_target['name']}_dev",
                    out=f"test_bin/{bin_target['name']}",
                    is_executable=True,
                    tags=TEST_GRAPH_TAGS,
                ))

    # --- tests (dev graph only) ---
    g = graph(True)
    normal_deps, normal_macros = ws.first_party_deps(package, {None}, True)
    dev_deps, dev_macros = ws.first_party_deps(package, {None, "dev"}, True)
    build_dep = [":build_script_dev"] if build_mode == "cargo" else []
    workspace_rust_data = "//:workspace_rust_sources"

    test_names: set[str] = set()

    def add_test(target_name: str, binary_id: str, sources: str, attrs: dict, manual_reason: str | None) -> None:
        if target_name in test_names:
            raise SystemExit(f"{name}: duplicate Bazel test target {target_name}")
        test_names.add(target_name)
        data = ["//:workspace_test_data"]
        if READS_WORKSPACE_SOURCES.search(sources):
            data.append(workspace_rust_data)
        data += attrs.pop("extra_data", [])
        if 'env!("CARGO")' in sources:
            # Cargo sets CARGO for every compile; tests that run `cargo
            # metadata` get the toolchain's cargo.
            data.append(CARGO_FILES)
            attrs["rustc_env"] = (attrs.get("rustc_env") or {}) | {"CARGO": f"$(execpath {CARGO_FILES})"}
        fixtures = FIXTURE_TESTS.get(name, []) if binary_id == name else []
        fixture_patterns = sorted({p for p, _ in fixtures})
        serial = [
            p for p in nextest.serial_patterns(binary_id, sources)
            if not any(f in p for f in fixture_patterns)
        ]
        if binary_id in nextest.exclusive_binaries:
            serial = []
        base_tags = TEST_GRAPH_TAGS + (["manual"] if manual_reason else [])

        default_timeout = TEST_TIMEOUTS.get(
            (name, binary_id.split("::", 1)[-1]),
            # Bazel times out a whole test binary (nextest kills single tests at
            # 180 s). Unit-test binaries hold thousands of tests.
            "long" if "::" not in binary_id or "::bin/" in binary_id else None,
        )
        known = KNOWN_FAILING.get((name, binary_id.split("::", 1)[-1]), {})
        shards = MODULE_SHARDS.get(name, []) if binary_id == name and lib is not None else []
        # A binary split into several targets is compiled once, as
        # `<target>_binary`; the split targets run it through shared_binary_test. The
        # binary target itself only lists its tests, so it stays a normal
        # target that the clippy and rustfmt aspects reach.
        split = bool(shards or serial or known or fixture_patterns)

        def compile_rule(rule_name: str, args: list[str], tags: list[str], timeout: str | None, extra: dict) -> None:
            rules.append(Rule(
                "rust_test",
                name=rule_name,
                timeout=timeout,
                **attrs,
                compile_data=Raw('["//:workspace_test_data"]'),
                data=data,
                **common,
                crate_features=g["features"],
                lint_config=lint_config,
                args=args or None,
                **extra,
                tags=sorted(set(base_tags + tags)) or None,
            ))

        if split:
            used.add("shared_binary_test")
            compile_rule(f"{target_name}_binary", ["--list"], [], None, {})

        def emit(suffix: str, args: list[str], tags: list[str], extra: dict) -> None:
            timeout = extra.pop("timeout", None) or default_timeout
            if not split:
                compile_rule(target_name + suffix, args, tags, timeout, extra)
                return
            rules.append(Rule(
                "shared_binary_test",
                name=target_name + suffix,
                binary=f":{target_name}_binary",
                timeout=timeout,
                args=args or None,
                **extra,
                tags=sorted(set(base_tags + tags)) or None,
            ))

        skips = [a for p in fixture_patterns + serial for a in ("--skip", p)]
        skips += [a for t in sorted(known) for a in ("--skip", t)]
        exclusive = ["exclusive"] if binary_id in nextest.exclusive_binaries else []
        if manual_reason:
            rules.append(Comment(f"manual: {manual_reason}"))
        if shards:
            # Select by real top-level module (bazel/module_shard_test.sh):
            # libtest filters are substring matches, so a `tests::` filter
            # would also take every nested `foo::tests::`.
            for index, bucket in enumerate(shards, 1):
                reason = MANUAL_SHARDS.get((name, index))
                if reason:
                    rules.append(Comment(f"manual: {reason}"))
                # A nested path listed in another shard overrides this one's
                # enclosing module (`tests::rules` vs `tests`).
                nested = sorted(m for other in shards if other is not bucket for m in other
                                if any(m.startswith(f"{b}::") for b in bucket))
                emit(
                    f"_shard{index}",
                    skips,
                    exclusive + (["manual"] if reason else []),
                    {"include_modules": bucket, **({"exclude_modules": nested} if nested else {}),
                     **({"timeout": "eternal"} if reason else {})},
                )
            listed = {m for b in shards for m in b}
            outer = sorted(m for m in listed if not any(m.startswith(f"{o}::") for o in listed))
            emit("_shard_rest", skips, exclusive, {"exclude_modules": outer})
        else:
            emit("", skips, exclusive, {})
        if serial:
            # nextest runs these in a serialized test-group or with every test
            # thread reserved; run them one at a time with nothing else alongside.
            emit("_serial", serial + ["--test-threads=1"], ["exclusive"], {})
        if known:
            for test, reason in sorted(known.items()):
                rules.append(Comment(f"manual: {test}: {reason}"))
            emit("_known_failing", sorted(known) + ["--exact"], ["manual"], {})
        if fixture_patterns:
            env_names = sorted({v for _, v in fixtures})
            rules.append(Comment(f"manual: needs {', '.join(env_names)} from the client environment"))
            emit("_fixture", fixture_patterns, ["exclusive", "manual"], {"env_inherit": env_names})

    if lib is not None and lib.get("test", True):
        add_test(
            "lib_test",
            name,
            crate_sources(pkg_root, "src/**/*.rs"),
            {
                "crate": f":{lib['name']}_dev",
                "aliases": Raw("dev_aliases(normal_dev = True, proc_macro_dev = True)"),
                "proc_macro_deps": concat("dev_crate_deps(proc_macro_dev = True)", sorted(set(dev_macros) - set(normal_macros))),
                "rustc_env": test_env or None,
                "deps": concat("dev_crate_deps(normal_dev = True)", sorted(set(dev_deps) - set(normal_deps))),
            },
            None,
        )

    for bin_target in bins:
        if not bin_target.get("test", True):
            continue
        extra = list(dev_deps + build_dep)
        if lib is not None and not is_proc_macro:
            extra.append(f":{lib['name']}_dev")
        add_test(
            f"bin_{bin_target['name']}_test",
            f"{name}::bin/{bin_target['name']}",
            crate_sources(pkg_root, "src/**/*.rs"),
            {
                "srcs": Raw(SRC_GLOB),
                "crate_root": relative_src(package, bin_target),
                "aliases": Raw("dev_aliases(normal_dev = True, proc_macro_dev = True)"),
                "proc_macro_deps": concat("dev_crate_deps(proc_macro = True, proc_macro_dev = True)", dev_macros),
                "rustc_env": test_env or None,
                "rustc_env_files": None,
                "deps": concat("dev_crate_deps(normal = True, normal_dev = True)", sorted(set(extra))),
            },
            None,
        )

    # Integration tests: bazel/rust_integration_tests.bzl globs tests/*.rs and
    # tests/*/main.rs, so a new test file needs no regeneration. Only tests
    # that deviate from the crate's defaults are named here (`overrides`), and
    # tests split into several targets are written out as explicit rules
    # (`exclude`). Every crate gets the call, so its first test file needs no
    # regeneration either.
    bin_env = {
        f"CARGO_BIN_EXE_{b['name']}": f"$(execpath :{b['name']}_test_bin)" for b in bins
    }
    extra = list(dev_deps)
    macros = list(dev_macros)
    if lib is not None:
        (macros if is_proc_macro else extra).append(f":{lib['name']}_dev")
    integration_attrs = {
        "aliases": Raw("dev_aliases(normal_dev = True, proc_macro_dev = True)"),
        "proc_macro_deps": concat("dev_crate_deps(proc_macro = True, proc_macro_dev = True)", sorted(set(macros))),
        "rustc_env": test_env | bin_env or None,
        "deps": concat("dev_crate_deps(normal = True, normal_dev = True)", sorted(set(extra))),
    }
    shared_test_sources = crate_sources(pkg_root, "tests/*/**/*.rs")
    crate_reads_sources = bool(READS_WORKSPACE_SOURCES.search(shared_test_sources))
    discovered = dict(integration_test_roots(pkg_root))
    overrides: dict[str, dict] = {}
    exclude: set[str] = {n for n in discovered if n not in {t["name"] for t in tests}}
    for test in sorted(tests, key=lambda t: t["name"]):
        root = relative_src(package, test)
        in_subdir = root.count("/") > 1
        binary_id = f"{name}::{test['name']}"
        missing = sorted(set(test.get("required-features") or []) - set(ws.dev_features[name]))
        reason = MANUAL_TESTS.get((name, test["name"]))
        if missing and not reason:
            reason = (
                f"required-features {', '.join(missing)} are off in `cargo test --workspace`; "
                "Cargo CI runs it with --features"
            )
        sources = (pkg_root / root).read_text(errors="replace") + shared_test_sources
        exclusive = binary_id in nextest.exclusive_binaries
        split = (not exclusive and nextest.serial_patterns(binary_id, sources)) or (name, test["name"]) in KNOWN_FAILING
        if discovered.get(test["name"]) == root and not split:
            override: dict[str, object] = {}
            if 'env!("CARGO")' in sources:
                override["cargo"] = True
            if exclusive:
                override["exclusive"] = True
            if reason:
                override["manual"] = reason
            if (name, test["name"]) in TEST_TIMEOUTS:
                override["timeout"] = TEST_TIMEOUTS[(name, test["name"])]
            if (READS_WORKSPACE_SOURCES.search(sources) and not crate_reads_sources
                    and not reads_workspace_sources_by_name(test["name"])):
                override["workspace_sources"] = True
            if override:
                overrides[test["name"]] = override
            continue
        if test["name"] in discovered:
            exclude.add(test["name"])
        add_test(
            test["name"],
            f"{name}::{test['name']}",
            sources,
            {
                "srcs": Raw("TEST_SUPPORT_SRCS" if in_subdir else f'["{root}"] + TEST_SUPPORT_SRCS'),
                "crate_root": root,
                **integration_attrs,
                "extra_data": [f":{b['name']}_test_bin" for b in bins],
            },
            reason,
        )

    used.add("rust_integration_tests")
    rules.append(Rule(
        "rust_integration_tests",
        overrides=Raw(render_overrides(overrides)),
        exclude=sorted(exclude) or None,
        workspace_sources=True if crate_reads_sources else None,
        **integration_attrs,
        data=[f":{b['name']}_test_bin" for b in bins] or None,
        **common,
        crate_features=g["features"],
        lint_config=lint_config,
        tags=TEST_GRAPH_TAGS,
    ))

    # --- assemble ---
    out = [HEADER]
    out.append('load("@bazel_skylib//rules:copy_file.bzl", "copy_file")\n' if "copy_file" in used else "")
    out.append('load("@cargo_versions//:versions.bzl", "CARGO_VERSIONS")\n')
    out.append('load("@crates//:defs.bzl", "aliases", "all_crate_deps")\n')
    out.append('load("@crates_dev//:defs.bzl", dev_aliases = "aliases", dev_crate_deps = "all_crate_deps")\n')
    cargo_rules = sorted({"cargo_build_script"} & used | ({"extract_cargo_lints"} if lint_config else set()))
    if cargo_rules:
        out.append('load("@rules_rust//cargo:defs.bzl", ' + ", ".join(f'"{r}"' for r in cargo_rules) + ")\n")
    if "rust_integration_tests" in used:
        out.append('load("//bazel:rust_integration_tests.bzl", "rust_integration_tests")\n')
    if "shared_binary_test" in used:
        out.append('load("//bazel:shared_binary_test.bzl", "shared_binary_test")\n')
    rust_rules = sorted(used & {"rust_binary", "rust_library", "rust_proc_macro", "rust_test"})
    out.append('load("@rules_rust//rust:defs.bzl", ' + ", ".join(f'"{r}"' for r in rust_rules) + ")\n\n")
    out.append('package(default_visibility = ["//visibility:public"])\n\n')
    out.append("# The crate's current Cargo.toml version, read when Bazel loads the build.\n")
    out.append(f'CRATE_VERSION = CARGO_VERSIONS["{name}"]\n\n')
    out.append(
        "COMPILE_DATA = glob(\n    [\"**\"],\n    exclude = "
        + starlark_list(COMPILE_DATA_EXCLUDES, "    ")
        + ",\n    allow_empty = True,\n)\n\n"
    )
    included = included_fragments(pkg_root)
    out.append(
        "# Rust files pulled in with include!() rather than declared as modules. They\n"
        "# are compile data, not srcs, so the rustfmt aspect skips them as cargo fmt does.\n"
    )
    out.append(f"INCLUDED_SRCS = {starlark_list(included, '')}\n\n")
    out.append("# Shared modules of the integration tests (tests/<dir>/**), compiled into each.\n")
    out.append('TEST_SUPPORT_SRCS = glob(["tests/*/**/*.rs"], allow_empty = True)\n\n')
    out.append("\n".join(rule.render() for rule in rules))
    return "".join(out).rstrip("\n") + "\n"


class Comment(Rule):
    def __init__(self, text: str) -> None:
        super().__init__("")
        self.text = text

    def render(self) -> str:
        return f"# {self.text}"


def render_root(ws: Workspace) -> str:
    bins = [
        (ws.package_dir(p).as_posix(), t["name"])
        for p in ws.packages
        for t in p["targets"]
        if "bin" in t["kind"]
    ]
    out = [HEADER, "# Bazel build for intentd, alongside Cargo. See bazel/README.md.\n\n"]
    out.append(Rule("exports_files", srcs=Raw('["Cargo.lock", "Cargo.toml", "rust-toolchain.toml"]')).render()
               .replace("exports_files(\n    srcs = ", "exports_files(").replace(",\n)", ")"))
    for pkg_dir, bin_name in sorted(bins, key=lambda b: b[1]):
        out.append("\n" + Rule("alias", name=bin_name, actual=f"//{pkg_dir}:{bin_name}").render())
    crate_dirs = [ws.package_dir(p).as_posix() for p in ws.packages]
    out.append("\n# Run-time inputs of every test: all non-Rust workspace files (fixtures,\n")
    out.append("# goldens, scripts, workflow files). Tests read some of them across crates.\n")
    out.append(Rule(
        "filegroup",
        name="workspace_test_data",
        srcs=concat(f"glob({starlark_list(ROOT_TEST_DATA)}, allow_empty = True)",
                    ROOT_TEST_DATA_FILES + [f"//{d}:test_data_files" for d in crate_dirs]),
        visibility=["//visibility:public"],
    ).render())
    out.append("\n# Rust sources of every crate, for the source lints that walk the workspace.\n")
    out.append(Rule(
        "filegroup",
        name="workspace_rust_sources",
        srcs=[f"//{d}:rust_source_files" for d in crate_dirs],
        visibility=["//visibility:public"],
    ).render())
    return "".join(out)


def render_module(ws: Workspace) -> str:
    manifests = ["//:Cargo.toml"] + sorted(
        f"//{ws.package_dir(p).as_posix()}:Cargo.toml" for p in ws.packages
    )
    manifest_lines = "".join(f'        "{m}",\n' for m in manifests)
    version_tags = "".join(
        f'cargo_versions.crate(\n    name = "{p["name"]}",\n    manifest = "//{ws.package_dir(p).as_posix()}:Cargo.toml",\n)\n'
        for p in sorted(ws.packages, key=lambda p: p["name"])
    )
    return f'''{HEADER}
# Rust toolchain, pinned to rust-toolchain.toml's channel.
rust = use_extension("@rules_rust//rust:extensions.bzl", "rust")
rust.toolchain(
    edition = "2021",
    versions = ["{rust_version()}"],
)
use_repo(rust, "rust_toolchains")

register_toolchains("@rust_toolchains//:all")

# Third-party crates, resolved from the Cargo workspace. Crate annotations
# (build-script environment, native-library tweaks) are in
# bazel/crates.MODULE.bazel and apply to both hubs.
crate = use_extension("@rules_rust//crate_universe:extensions.bzl", "crate")

# Production graph: the workspace without dev-dependencies, so features match
# `cargo build`. Its lockfile is Cargo.lock minus dev-only packages (same pins),
# because crate_universe writes the lock it resolved back to `cargo_lockfile`.
crate.from_cargo(
    name = "crates",
    cargo_lockfile = "//{PROD_WORKSPACE.as_posix()}:Cargo.lock",
    manifests = ["//{PROD_WORKSPACE.as_posix()}:Cargo.toml"],
)

# Test graph: the real workspace, features as `cargo test --workspace` unifies
# them (dev-dependencies included). Only test targets and their `_dev`
# first-party libraries use it.
crate.from_cargo(
    name = "crates_dev",
    cargo_lockfile = "//:Cargo.lock",
    manifests = [
{manifest_lines}    ],
)
use_repo(crate, "crates", "crates_dev")

# Workspace-crate versions, read from these manifests whenever they change
# (bazel/cargo_versions.bzl), so release bumps need no Bazel action.
cargo_versions = use_extension("//bazel:cargo_versions.bzl", "cargo_versions")
{version_tags}use_repo(cargo_versions, "cargo_versions")
'''


# --- production manifests ----------------------------------------------------

_HEADER_RE = re.compile(r"^\s*\[\[?([^\]]+)\]\]?\s*(#.*)?$")


def _dropped_table(name: str) -> bool:
    name = name.strip().replace("'", '"')
    return bool(
        name == "dev-dependencies"
        or name.startswith("dev-dependencies.")
        or re.match(r'^target\..*\.dev-dependencies(\..*)?$', name)
        or name in ("lib", "bin", "test", "bench", "example")
        or name.startswith("profile")
        or name.startswith("package.metadata")
    )


def strip_manifest(text: str, package_extra: str = "") -> str:
    out: list[str] = []
    skip = False
    for line in text.splitlines():
        match = _HEADER_RE.match(line)
        if match:
            skip = _dropped_table(match.group(1))
            if not skip and match.group(1).strip() == "package" and package_extra:
                out += [line, package_extra]
                continue
        if not skip:
            out.append(line)
    return "\n".join(out).rstrip("\n") + "\n"


def drop_member_versions(text: str) -> str:
    """Remove workspace-crate versions from a production manifest copy.

    release-plz bumps every workspace crate's version on each release. Feature
    resolution does not depend on them, so the copies omit the package version
    (Cargo then uses 0.0.0) and the `version` of path dependencies; the
    generated manifests and pruned lock stay unchanged across releases.
    """
    out = []
    section = ""
    for line in text.splitlines():
        match = _HEADER_RE.match(line)
        if match:
            section = match.group(1).strip()
        if section == "package" and re.match(r"^version(\.workspace)?\s*=", line):
            continue
        if re.search(r'\bpath\s*=\s*"', line):
            line = re.sub(r',?\s*\bversion\s*=\s*"[^"]*"', "", line)
        out.append(line)
    return "\n".join(out) + "\n"


def prod_workspace_files(ws: Workspace) -> dict[Path, str]:
    root = strip_manifest((ROOT / "Cargo.toml").read_text())
    root = re.sub(r'^exclude\s*=.*\n', "", root, flags=re.M)
    for path in re.findall(r'\bpath\s*=\s*"([^"]+)"', root):
        if path.split("/")[0] not in PROD_WORKSPACE_LINKS:
            raise SystemExit(f"root Cargo.toml path {path}: add its top directory to PROD_WORKSPACE_LINKS")
    files = {
        ROOT / PROD_WORKSPACE / "BUILD.bazel": HEADER + '\nexports_files([\n    "Cargo.lock",\n    "Cargo.toml",\n])\n',
        ROOT / PROD_WORKSPACE / "Cargo.toml": TOML_HEADER + "\n" + root,
    }
    for package in ws.packages:
        pkg_dir = ws.package_dir(package)
        build = ""
        sections = []
        for target in package["targets"]:
            src = relative_src(package, target)
            if "custom-build" in target["kind"]:
                build = f'build = "{src}"'
            elif "lib" in target["kind"]:
                sections.append(f'[lib]\nname = "{target["name"]}"\npath = "{src}"\n')
            elif "proc-macro" in target["kind"]:
                sections.append(f'[lib]\nname = "{target["name"]}"\npath = "{src}"\nproc-macro = true\n')
            elif "bin" in target["kind"]:
                sections.append(f'[[bin]]\nname = "{target["name"]}"\npath = "{src}"\n')
        body = drop_member_versions(strip_manifest(Path(package["manifest_path"]).read_text(), build))
        files[ROOT / PROD_WORKSPACE / pkg_dir / "Cargo.toml"] = (
            TOML_HEADER + "\n" + body + "\n" + "\n".join(sections)
        )
    files[ROOT / PROD_WORKSPACE / "Cargo.lock"] = pruned_lockfile(files)
    return files


def pruned_lockfile(files: dict[Path, str]) -> str:
    """Cargo.lock minus the dev-only packages, with every version unchanged.

    The production hub needs its own lockfile: crate_universe writes the lock it
    resolved back to `cargo_lockfile`, which must never touch the real
    Cargo.lock. Cargo only drops unused entries when it rereads a lock, so the
    result keeps Cargo.lock's pins.
    """
    with tempfile.TemporaryDirectory(prefix="bazel-gen-") as temp:
        temp_root = Path(temp)
        for path, content in files.items():
            if path.name == "Cargo.toml":
                target = temp_root / path.relative_to(ROOT)
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content)
        workspace = temp_root / PROD_WORKSPACE
        for entry in PROD_WORKSPACE_LINKS:
            (workspace / entry).symlink_to(ROOT / entry)
        shutil.copy(ROOT / "Cargo.lock", workspace / "Cargo.lock")
        for offline in (["--offline"], []):
            result = subprocess.run(
                ["cargo", "metadata", "--format-version", "1", *offline],
                cwd=workspace, capture_output=True, text=True,
            )
            if result.returncode == 0:
                break
        else:
            raise SystemExit(f"cargo could not read the production workspace:\n{result.stderr}")
        return (workspace / "Cargo.lock").read_text()


def generated_files() -> dict[Path, str]:
    ws = Workspace(cargo_metadata())
    nextest = NextestPolicy(ROOT / ".config" / "nextest.toml")
    files = {
        ROOT / "BUILD.bazel": render_root(ws),
        ROOT / "bazel" / "generated.MODULE.bazel": render_module(ws),
    }
    for package in ws.packages:
        files[ROOT / ws.package_dir(package) / "BUILD.bazel"] = render_build(ws, package, nextest)
    files.update(prod_workspace_files(ws))
    return files


def stale_label(path: Path, exists: bool, generated: bool) -> str:
    """How `--check` describes a stale file: a missing crate BUILD file means a new crate."""
    rel = path.relative_to(ROOT)
    crate_build = len(rel.parts) == 3 and rel.parts[0] == "crates" and rel.name == "BUILD.bazel"
    if not exists:
        return f"{rel} (missing{': new crate ' + rel.parts[1] if crate_build else ''})"
    if not generated:
        return f"{rel} (no longer generated{': removed crate ' + rel.parts[1] if crate_build else ''})"
    return str(rel)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if any generated file is stale")
    parser.add_argument("--suggest-shards", metavar="PACKAGE",
                        help="print a size-balanced MODULE_SHARDS entry for PACKAGE and exit")
    args = parser.parse_args(argv)

    if args.suggest_shards:
        ws = Workspace(cargo_metadata())
        package = ws.by_name[args.suggest_shards]
        count = len(MODULE_SHARDS.get(args.suggest_shards, [])) or 8
        shards = module_shards(ROOT / ws.package_dir(package), relative_src(package, lib_target(package)), count)
        print(json.dumps({args.suggest_shards: shards}, indent=4))
        return 0

    files = generated_files()
    stale = []
    for path, content in files.items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        stale.append(stale_label(path, current is not None, True))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)

    for entry in PROD_WORKSPACE_LINKS:
        link = ROOT / PROD_WORKSPACE / entry
        target = Path("../" * len(PROD_WORKSPACE.parts) + entry)
        if link.is_symlink() and Path(link.readlink()) == target:
            continue
        stale.append(str(link.relative_to(ROOT)))
        if not args.check:
            if link.is_symlink() or link.exists():
                link.unlink()
            link.symlink_to(target)

    leftovers = [
        p for p in sorted(ROOT.glob("crates/*/BUILD.bazel")) + sorted((ROOT / PROD_WORKSPACE).rglob("Cargo.toml"))
        if p not in files
    ]
    for path in leftovers:
        stale.append(stale_label(path, True, False))
        if not args.check:
            path.unlink()

    if args.check and stale:
        print("Bazel files are out of date with Cargo metadata:", file=sys.stderr)
        for path in stale:
            print(f"  {path}", file=sys.stderr)
        print(f"Run: {FIX_COMMAND}, then commit the files above and MODULE.bazel.lock.", file=sys.stderr)
        return 1
    for path in stale:
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
