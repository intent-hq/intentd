-- (migrations 0001-0196). Every table starts with tenant_id, and tenant_id
-- leads every primary key, unique constraint, index and foreign key, so a
-- cascade can never cross tenants. Tables with an SQLite rowid get row_seq
-- (insertion order). JSON stays text; see 0001_compat.sql.

