//! The `client.hello` capability golden (§5.17). intentd generates
//! `docs/protocol/fixtures/hello/capabilities.json` (monorepo) from
//! [`server_json`] and [`with_runtime_capabilities`], one profile per daemon
//! composition. The copy in `tests/fixtures/hello-capabilities.json` comes
//! through the monorepo's shared fixture-copy tool
//! (`scripts/hello-capabilities-contract.mjs`): its lock names the monorepo
//! commit and CI verifies the bytes. cloudlands-fe's fake daemon announces the
//! same file, so a capability added here without the fixture fails this test.
//!
//! To change a capability: run this test from a monorepo checkout with
//! `UPDATE_HELLO_CAPABILITIES=1` to rewrite the canonical file, land that docs
//! change, then re-export the copy from the merged commit.

use super::{server_json, with_runtime_capabilities};
use intent_core::settings_file::DaemonMode;
use serde_json::{json, Value};

const COPY: &str = include_str!("../../tests/fixtures/hello-capabilities.json");
const COPY_PATH: &str = "tests/fixtures/hello-capabilities.json";
const CANONICAL_PATH: &str = "docs/protocol/fixtures/hello/capabilities.json";
const DESCRIPTION: &str =
    "The server.capabilities a successful client.hello announces (section 5.17), \
    one profile per daemon composition. Generated by intentd \
    (crates/intent-transport/src/client/hello_capabilities_fixture.rs); do not edit by hand.";

struct Profile {
    id: &'static str,
    description: &'static str,
    mode: DaemonMode,
    startup_status: bool,
    remote_machines: bool,
}

const PROFILES: [Profile; 3] = [
    Profile {
        id: "regular",
        description: "The default desktop daemon: startup tracking and agent placement on exposed and cloud machines.",
        mode: DaemonMode::Regular,
        startup_status: true,
        remote_machines: true,
    },
    Profile {
        id: "orchestrator",
        description: "daemon.mode orchestrator: every agent runs on an exposed or cloud machine.",
        mode: DaemonMode::Orchestrator,
        startup_status: true,
        remote_machines: true,
    },
    Profile {
        id: "node",
        description: "daemon.mode node: runs agents for the backends it is exposed to and places none itself.",
        mode: DaemonMode::Node,
        startup_status: true,
        remote_machines: false,
    },
];

fn announced_server(profile: &Profile) -> Value {
    let frame = json!({ "jsonrpc": "2.0", "id": 1, "result": {
        "server": server_json(false, "linux", "x86_64", "fixture", None, true) } })
    .to_string();
    let frame = with_runtime_capabilities(
        Some(frame),
        profile.mode,
        profile.startup_status,
        profile.remote_machines,
    )
    .expect("hello frame");
    serde_json::from_str::<Value>(&frame).expect("hello json")["result"]["server"].take()
}

fn sorted(object: &Value) -> Value {
    let mut entries: Vec<_> = object
        .as_object()
        .expect("capabilities object")
        .iter()
        .collect();
    entries.sort_by(|a, b| a.0.cmp(b.0));
    Value::Object(
        entries
            .into_iter()
            .map(|(k, v)| (k.clone(), v.clone()))
            .collect(),
    )
}

/// The fixture bytes, in the monorepo's `JSON.stringify(value, null, 2)` form.
fn generated() -> String {
    let profiles: Vec<Value> = PROFILES
        .iter()
        .map(|profile| {
            let server = announced_server(profile);
            json!({
                "id": profile.id,
                "description": profile.description,
                "daemonMode": server["daemonMode"],
                "startupStatus": profile.startup_status,
                "remoteMachines": profile.remote_machines,
                "capabilities": sorted(&server["capabilities"]),
            })
        })
        .collect();
    let doc = json!({
        "fixtureFormatVersion": 1,
        "description": DESCRIPTION,
        "profiles": profiles,
    });
    format!(
        "{}\n",
        serde_json::to_string_pretty(&doc).expect("fixture json")
    )
}

/// Per-profile capability differences, `-` for the fixture and `+` for the code.
fn differences(fixture: &Value, code: &Value) -> Vec<String> {
    let mut lines = Vec::new();
    let profiles = |doc: &Value| doc["profiles"].as_array().cloned().unwrap_or_default();
    for ours in profiles(code) {
        let id = ours["id"].as_str().unwrap_or_default().to_owned();
        let Some(theirs) = profiles(fixture)
            .into_iter()
            .find(|p| p["id"] == ours["id"])
        else {
            lines.push(format!("{id}: profile missing from the fixture"));
            continue;
        };
        let empty = serde_json::Map::new();
        let a = theirs["capabilities"].as_object().unwrap_or(&empty);
        let b = ours["capabilities"].as_object().unwrap_or(&empty);
        for (key, value) in a {
            if b.get(key) != Some(value) {
                lines.push(format!("{id}: - {key}: {value}"));
            }
        }
        for (key, value) in b {
            if a.get(key) != Some(value) {
                lines.push(format!("{id}: + {key}: {value}"));
            }
        }
        for field in [
            "daemonMode",
            "startupStatus",
            "remoteMachines",
            "description",
        ] {
            if theirs[field] != ours[field] {
                lines.push(format!(
                    "{id}: {field} {} -> {}",
                    theirs[field], ours[field]
                ));
            }
        }
    }
    lines
}

#[test]
fn hello_capabilities_match_the_protocol_fixture() {
    let generated = generated();
    if std::env::var_os("UPDATE_HELLO_CAPABILITIES").is_some() {
        let monorepo = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../..");
        let canonical = monorepo.join(CANONICAL_PATH);
        assert!(
            monorepo.join("docs/protocol").is_dir(),
            "UPDATE_HELLO_CAPABILITIES writes {CANONICAL_PATH}: run it from a monorepo checkout"
        );
        std::fs::create_dir_all(canonical.parent().expect("fixture directory"))
            .expect("create fixture directory");
        std::fs::write(&canonical, &generated).expect("write canonical fixture");
        return;
    }
    let fixture: Value = serde_json::from_str(COPY).expect("fixture json");
    let code: Value = serde_json::from_str(&generated).expect("generated json");
    assert!(
        fixture == code,
        "client.hello capabilities differ from {COPY_PATH}:\n{}\n\
         Docs lead: from a monorepo checkout, rerun this test with UPDATE_HELLO_CAPABILITIES=1 to \
         rewrite {CANONICAL_PATH}, land it, then re-export the copy with \
         scripts/hello-capabilities-contract.mjs export.",
        differences(&fixture, &code).join("\n")
    );
}
